#!/usr/bin/env python3
"""Writes the screenshot gallery into README.md (between the gallery markers) from tools/gallery.py.

usage: readme_gallery.py [--check]     --check: fail if README.md is out of date (CI)
"""
import html
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import gallery  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
START, END = "<!-- gallery:start -->", "<!-- gallery:end -->"


def table(device, cols, width):
    shots = [s for s in gallery.SHOTS if s[0] == device]
    rows = []
    for i in range(0, len(shots), cols):
        cells = []
        for _, name, title, desc, tags in shots[i:i + cols]:
            path = f"docs/screenshots/{device}/{name}"
            alt = html.escape(f"tv-hero {'on the TV' if device == 'tv' else 'phone app'}: {title}. {desc}")
            meta = " · ".join(gallery.label(t) for t in tags)
            cells.append(f'<td valign="top" width="{100 // cols}%"><a href="{path}"><img src="{path}" width="{width}" alt="{alt}"></a>'
                         f"<br><b>{html.escape(title)}</b><br><sub>{html.escape(meta)}</sub></td>")
        rows.append("<tr>" + "".join(cells) + "</tr>")
    return "<table>\n" + "\n".join(rows) + "\n</table>"


def block():
    tv = [s for s in gallery.SHOTS if s[0] == "tv"]
    ph = [s for s in gallery.SHOTS if s[0] == "phone"]
    return "\n".join([
        START,
        "<!-- Generated by tools/readme_gallery.py from tools/gallery.py: edit those, then run it. -->",
        f"<details open>\n<summary><b>📺 On the TV</b> ({len(tv)} screens: lock screens, Earn Time, Parent Menu, tools)</summary>\n",
        table("tv", 3, 280),
        "\n</details>\n",
        f"<details open>\n<summary><b>📱 On the phone</b> ({len(ph)} screens: family, apps, remote, setup, security)</summary>\n",
        table("phone", 6, 130),
        "\n</details>\n",
        "Screens are rendered with made-up sample families. Click any screen for full size, or browse them with filters on the "
        "[website gallery](https://ajitpal.github.io/tv-hero/gallery.html).",
        END,
    ])


def main():
    readme = ROOT / "README.md"
    text = readme.read_text()
    if START not in text:
        sys.exit("README.md has no gallery markers")
    new = text[:text.index(START)] + block() + text[text.index(END) + len(END):]
    if "--check" in sys.argv:
        if new != text:
            sys.exit("README gallery is out of date: run tools/readme_gallery.py")
        print("README gallery up to date")
        return
    readme.write_text(new)
    print(f"README gallery: {len(gallery.SHOTS)} screens")


if __name__ == "__main__":
    main()
