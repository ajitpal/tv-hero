#!/usr/bin/env python3
"""Keeps the release status in step everywhere from one source: CHANGELOG.md's newest heading.

- docs/ROADMAP.md: a release whose version has a CHANGELOG section is marked "Released (x.y.z)".
- README.md, between the roadmap markers: the latest release (linked) and what's next, from ROADMAP.md.

So shipping a release (a new CHANGELOG section, which check_release.py already requires) only needs
this run once; CI runs it with --check and fails if either file is behind.

usage: readme_roadmap.py [--check]     --check: fail if README.md or docs/ROADMAP.md is out of date (CI)
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
START, END = "<!-- roadmap:start -->", "<!-- roadmap:end -->"
ROW = re.compile(r"^\| (\*\*)?([^|*]+?)(\*\*)? \| ([^|]+?) \| ([^|]+?) \|$")


def released(changelog):
    """Every version with a CHANGELOG section, newest first."""
    return re.findall(r"^## (\d+\.\d+\.\d+)\s*$", changelog, re.M)


def minor(v):
    return ".".join(v.split(".")[:2])


def update_roadmap(roadmap, versions):
    """ROADMAP.md with each released minor version's status set to 'Released (newest patch)'."""
    newest = {}
    for v in versions:   # newest first, so the first patch seen for a minor is its newest
        newest.setdefault(minor(v), v)
    out = []
    for line in roadmap.split("\n"):
        m = ROW.match(line)
        if m and m.group(2) in newest:
            line = f"| **{m.group(2)}** | {m.group(4)} | Released ({newest[m.group(2)]}) |"
        out.append(line)
    return "\n".join(out)


def upcoming(roadmap):
    """(release, theme, status) rows of the roadmap's table that aren't released yet."""
    rows = []
    for line in roadmap.split("\n"):
        m = ROW.match(line)
        if not m or m.group(2) in ("Release",) or m.group(5).startswith("Released"):
            continue
        rows.append((m.group(2).strip(), m.group(4).strip(), m.group(5).strip()))
    return rows


def block(latest, rows):
    lines = [START, "<!-- Generated by tools/readme_roadmap.py from CHANGELOG.md and docs/ROADMAP.md: edit those, then run it. -->",
             f"**Latest release: [{latest}](https://github.com/ajitpal/tv-hero/releases/latest)** · [what's new](CHANGELOG.md)",
             "", "| Release | Theme | Status |", "|---|---|---|"]
    for r, theme, status in rows:
        lines.append(f"| **{r}** | {theme} | {status} |")
    lines.append(END)
    return "\n".join(lines)


def main():
    changelog = (ROOT / "CHANGELOG.md").read_text()
    versions = released(changelog)
    if not versions:
        sys.exit("CHANGELOG.md has no '## x.y.z' section")
    roadmap_path, readme_path = ROOT / "docs/ROADMAP.md", ROOT / "README.md"
    roadmap = roadmap_path.read_text()
    new_roadmap = update_roadmap(roadmap, versions)
    readme = readme_path.read_text()
    if START not in readme or END not in readme:
        sys.exit("README.md has no roadmap markers")
    new_readme = readme[:readme.index(START)] + block(versions[0], upcoming(new_roadmap)) + readme[readme.index(END) + len(END):]
    if "--check" in sys.argv:
        behind = [n for n, a, b in (("docs/ROADMAP.md", roadmap, new_roadmap), ("README.md", readme, new_readme)) if a != b]
        if behind:
            sys.exit("Release status is out of date in " + " and ".join(behind) + ": run tools/readme_roadmap.py")
        print(f"README and roadmap up to date (latest {versions[0]})")
        return
    roadmap_path.write_text(new_roadmap)
    readme_path.write_text(new_readme)
    print(f"README and roadmap: latest {versions[0]}, {len(upcoming(new_roadmap))} releases next")


if __name__ == "__main__":
    main()
